# frozen_string_literal: true

require 'shellwords'
require 'yaml'

module CertManager
  # Generates bash and zsh completion scripts from the CLI command registry,
  # and answers the `__complete` callbacks those scripts make for dynamic
  # values (certificate, provider and zone names). Because everything is
  # derived from CLI.commands, new commands and flags complete automatically.
  module Completions
    SHELLS = %w[bash zsh].freeze
    HIDDEN_GROUP = :hidden

    module_function

    # @param explicit [String, nil] shell given on the command line
    # @param env_shell [String, nil] value of $SHELL
    # @return [String] one of SHELLS
    # @raise [CLI::UsageError] when it cannot be determined or is unsupported
    def detect_shell(explicit = nil, env_shell = ENV['SHELL'])
      shell = explicit || File.basename(env_shell.to_s)
      return shell if SHELLS.include?(shell)

      source = explicit ? "'#{explicit}'" : "$SHELL ('#{env_shell}')"
      raise CLI::UsageError, "Unsupported shell #{source}; choose one of: #{SHELLS.join(', ')}"
    end

    # @return [String] the completion script
    def generate(shell, program:, executable:)
      raise ArgumentError, "Unsupported shell '#{shell}'" unless SHELLS.include?(shell)

      send(shell, program, executable)
    end

    def commands
      CLI.commands.values.reject { |c| c.group == HIDDEN_GROUP }
    end

    # Options a command accepts, as [Option] (declared globals, own options, help)
    def options_for(cmd)
      cmd.options + cmd.globals.map { |k| CLI::GLOBAL_OPTIONS.fetch(k) } + [CLI.help_option]
    end

    def flags_for(cmd)
      options_for(cmd).flat_map(&:flags)
    end

    # Flags that take a value (needed to tell values from positional arguments)
    def value_flags
      (commands.flat_map { |c| options_for(c) } + [CLI::GLOBAL_OPTIONS[:config]]).select(&:arg).flat_map(&:flags).uniq
    end

    def file_flags
      commands.flat_map { |c| options_for(c) }.select { |o| o.arg == 'PATH' }.flat_map(&:flags).uniq
    end

    # { flag => [values] } for options with a fixed set of values
    def enum_flags
      commands.flat_map { |c| options_for(c) }.select(&:values).flat_map { |o| o.flags.map { |f| [f, o.values] } }.to_h
    end

    # Candidates for dynamic completion kinds
    # @param kind [String] command, type, shell, certificate, provider or zone
    # @param config_path [String, nil] -c value
    # @param context [String, nil] e.g. the provider whose zones to list
    # @return [Array<String>]
    def candidates(kind, config_path = nil, context = nil)
      case kind
      when 'command' then commands.map(&:name)
      when 'type' then DNSProviders.available_types
      when 'shell' then SHELLS
      when 'certificate' then certificate_names(raw_config(config_path))
      when 'provider' then provider_settings(raw_config(config_path)).keys
      when 'zone' then zones(raw_config(config_path), context)
      else []
      end
    rescue StandardError
      []
    end

    def raw_config(path)
      file = Config.resolve_path(path)
      File.exist?(file) ? (YAML.safe_load(File.read(file), permitted_classes: [Symbol]) || {}) : {}
    end

    def provider_settings(doc)
      (doc.fetch('version', 1) == 1 ? doc['dns_providers'] : doc['providers']) || {}
    end

    def certificate_names(doc)
      (doc['certificates'] || []).map { |c| c['name'] || c['domains']&.first }.compact
    end

    def zones(doc, provider)
      settings = provider_settings(doc)
      settings = settings.slice(provider) if provider && !provider.empty?
      settings.values.flat_map { |s| s['zones'] || [] }.uniq.sort
    end

    # [command, 1-based position, kind] for every positional argument that completes dynamically
    def positional_kinds
      commands.flat_map do |cmd|
        cmd.args.each_with_index.filter_map { |arg, i| [cmd.name, i + 1, arg.kind] if arg.kind }
      end
    end

    def bash(program, executable)
      exe = Shellwords.escape(executable)
      fn = "_#{program.gsub(/\W/, '_')}"
      <<~BASH
        # bash completion for #{program} (generated by `#{program} completions bash`)
        #{fn}() {
          local cur prev cmd cfg i word pos kind flags
          cur="${COMP_WORDS[COMP_CWORD]}"
          prev="${COMP_WORDS[COMP_CWORD-1]}"
          COMPREPLY=()

          # Find the command, the -c value and the positional index of the word being completed
          cmd="" cfg="" pos=0
          i=1
          while [ $i -lt $COMP_CWORD ]; do
            word="${COMP_WORDS[i]}"
            case "$word" in
              -c|--config) cfg="${COMP_WORDS[i+1]}"; i=$((i+1)) ;;
              #{value_flags.reject { |f| %w[-c --config].include?(f) }.join('|')}) i=$((i+1)) ;;
              -*) ;;
              *) if [ -z "$cmd" ]; then cmd="$word"; else pos=$((pos+1)); fi ;;
            esac
            i=$((i+1))
          done

          case "$prev" in
            #{file_flags.join('|')}) COMPREPLY=( $(compgen -f -- "$cur") ); return 0 ;;
        #{enum_flags.map { |flag, values| "    #{flag}) COMPREPLY=( $(compgen -W '#{values.join(' ')}' -- \"$cur\") ); return 0 ;;" }.join("\n")}
          esac

          if [ -z "$cmd" ]; then
            if [[ "$cur" == -* ]]; then
              flags="#{(CLI::ALL_GLOBALS.flat_map { |k| CLI::GLOBAL_OPTIONS[k].flags } + %w[-V --version -h --help -r --reason]).join(' ')}"
              COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
            else
              COMPREPLY=( $(compgen -W "#{commands.map(&:name).join(' ')}" -- "$cur") )
            fi
            return 0
          fi

          if [[ "$cur" == -* ]]; then
            case "$cmd" in
        #{commands.map { |c| "      #{c.name}) flags=\"#{flags_for(c).join(' ')}\" ;;" }.join("\n")}
            esac
            COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
            return 0
          fi

          pos=$((pos+1))
          kind=""
          case "$cmd:$pos" in
        #{positional_kinds.map { |name, i, kind| "      #{name}:#{i}) kind=#{kind} ;;" }.join("\n")}
          esac
          [ -z "$kind" ] && return 0

          local extra=""
          [ "$kind" = zone ] && extra="${COMP_WORDS[COMP_CWORD-1]}"
          COMPREPLY=( $(compgen -W "$(#{exe} ${cfg:+-c "$cfg"} __complete "$kind" "$extra" 2>/dev/null)" -- "$cur") )
          return 0
        }
        complete -F #{fn} #{program}
      BASH
    end

    def zsh(program, executable)
      exe = Shellwords.escape(executable)
      fn = "_#{program.gsub(/\W/, '_')}"
      <<~ZSH
        #compdef #{program}
        # zsh completion for #{program} (generated by `#{program} completions zsh`)

        # Dynamic values come from `#{program} __complete KIND [CONTEXT]`
        #{fn}_dynamic() {
          local kind=$1 extra=$2 cfg i
          local -a reply
          for (( i = 1; i < ${#words[@]}; i++ )); do
            [[ ${words[i]} == (-c|--config) ]] && cfg=${words[i+1]}
          done
          [[ -z $cfg ]] && cfg=$#{fn}_cfg
          reply=( ${(f)"$(#{exe} ${cfg:+-c $cfg} __complete $kind $extra 2>/dev/null)"} )
          compadd -a reply
        }
        #{fn}_certificate() { #{fn}_dynamic certificate }
        #{fn}_provider() { #{fn}_dynamic provider }
        #{fn}_zone() { #{fn}_dynamic zone ${line[1]} }
        #{fn}_type() { #{fn}_dynamic type }
        #{fn}_shell() { #{fn}_dynamic shell }
        #{fn}_command() { #{fn}_dynamic command }

        #{fn}() {
          local curcontext="$curcontext" state line ret=1
          typeset -A opt_args
          local -a commands
          commands=(
        #{commands.map { |c| "    #{zsh_quote("#{c.name}:#{c.summary}")}" }.join("\n")}
          )

          _arguments -C \\
        #{zsh_option_specs(CLI::ALL_GLOBALS.map { |k| CLI::GLOBAL_OPTIONS[k] } + [CLI.version_option, CLI.help_option, CLI::Option.new(key: :reason, short: '-r', long: '--reason', arg: 'REASON', desc: 'Revocation reason', values: CLI::REVOCATION_REASONS)], '    ')} \\
            '1: :->command' \\
            '*:: :->args' && ret=0

          case $state in
            command)
              _describe -t commands 'command' commands && ret=0
              ;;
            args)
              #{fn}_cfg=${opt_args[-c]:-${opt_args[--config]}}
              case $words[1] in
        #{commands.map { |c| zsh_command_case(fn, c) }.join("\n")}
              esac
              ;;
          esac
          return ret
        }

        if [ "$funcstack[1]" = "#{fn}" ]; then
          #{fn} "$@"
        else
          compdef #{fn} #{program}
        fi
      ZSH
    end

    def zsh_command_case(fn, cmd)
      specs = zsh_option_specs(options_for(cmd), '          ')
      positional = cmd.args.each_with_index.map do |arg, i|
        action = arg.kind ? "#{fn}_#{arg.kind}" : ' '
        "'#{i + 1}:#{arg.name}:#{action.strip.empty? ? '' : action}'"
      end
      body = [specs, *positional.map { |p| "          #{p}" }].reject(&:empty?).join(" \\\n")
      "        #{cmd.name})\n          _arguments \\\n#{body} && ret=0\n          ;;"
    end

    def zsh_option_specs(opts, indent)
      opts.map do |o|
        desc = zsh_escape(o.desc)
        value = if o.values then ":#{o.arg}:(#{o.values.join(' ')})"
                elsif o.arg == 'PATH' then ":#{o.arg}:_files"
                elsif o.arg then ":#{o.arg}: "
                else ''
                end
        if o.short && o.long
          excl = "(#{o.short} #{o.long})"
          "#{indent}'#{excl}'{#{o.short},#{o.long}}'[#{desc}]#{value}'"
        else
          "#{indent}'#{o.short || o.long}[#{desc}]#{value}'"
        end
      end.join(" \\\n")
    end

    def zsh_escape(text)
      text.gsub("'", %q('\\\\'')).gsub(/[\[\]:]/) { |c| "\\#{c}" }
    end

    def zsh_quote(text)
      "'" + text.gsub("'") { "'\\''" } + "'"
    end
  end
end
